#!/usr/bin/env python3
"""E1b/E1c — LLM-labelled chat sentiment vs market-adjusted forward returns.

Usage: python3 llm_classify_rerun.py <to_classify.tsv> <bars.ndjson> <labels.tsv>

  to_classify.tsv : message_id \t epoch \t author \t tickers_csv \t content
  labels.tsv      : row_index \t TICKER \t bull|bear      (one line per ticker per message)

Reports THREE things, and the third is the one that matters:
  1. raw overlapping-window t-stats        (optimistic — mentions cluster in time)
  2. clustered by (symbol, hour, direction) (honest — one obs per cluster)
  3. permutation p-value on the clustered spread

See ../PLAN-2026-08-21-position-context-correlator.md for the 2026-08-21 numbers.
Bullish signal did NOT survive clustering; bearish did (p=0.0455). Do not cite (1) alone.
"""
import json, sys, math, random, datetime, collections, statistics as st

HOR = [5, 15, 30, 60]
BENCH = "SPY"          # market benchmark; excluded from the tested universe

def load_bars(path):
    bars = collections.defaultdict(dict)
    for line in open(path):
        b = json.loads(line)
        ts = int(datetime.datetime.strptime(b["t"][:19], "%Y-%m-%dT%H:%M:%S")
                 .replace(tzinfo=datetime.timezone.utc).timestamp()) // 60
        bars[b["s"]][ts] = b["c"]
    return bars

def fwd(bars, sym, m0, k):
    a = bars[sym].get(m0)
    if a is None:
        for d in (1, 2, 3):
            a = bars[sym].get(m0 + d)
            if a is not None: m0 += d; break
    b = bars[sym].get(m0 + k)
    return None if (a is None or b is None or a <= 0) else (b - a) / a * 100

def tstat(v, minn=8):
    if len(v) < minn: return 0.0
    sd = st.pstdev(v)
    return 0.0 if sd == 0 else st.mean(v) / (sd / math.sqrt(len(v)))

def main(msg_path, bars_path, labels_path):
    bars = load_bars(bars_path)
    msgs = [l.rstrip("\n").split("\t") for l in open(msg_path)]
    labels = collections.defaultdict(list)
    for line in open(labels_path):
        p = line.rstrip("\n").split("\t")
        if len(p) == 3: labels[int(p[0])].append((p[1], p[2]))

    adj = {t: {k: [] for k in HOR} for t in ("bull", "bear")}
    obs30 = []
    for idx, row in enumerate(msgs):
        if idx not in labels or len(row) < 5: continue
        m0 = int(row[1]) // 60
        for sym, tag in labels[idx]:
            if sym == BENCH: continue
            for k in HOR:
                r, mkt = fwd(bars, sym, m0, k), fwd(bars, BENCH, m0, k)
                if r is None or mkt is None: continue
                adj[tag][k].append(r - mkt)
                if k == 30: obs30.append((sym, m0 // 60, tag, r - mkt))

    print("=== (1) RAW, overlapping windows — OPTIMISTIC ===")
    print(f"{'hor':>4} | {'bull n':>7}{'mean%':>9}{'t':>7} | {'bear n':>7}{'mean%':>9}{'t':>7}")
    for k in HOR:
        bl, br = adj["bull"][k], adj["bear"][k]
        if len(bl) < 8 or len(br) < 8: continue
        print(f"{k:>3}m | {len(bl):>7}{st.mean(bl):>9.3f}{tstat(bl):>7.2f} |"
              f" {len(br):>7}{st.mean(br):>9.3f}{tstat(br):>7.2f}")

    cl = collections.defaultdict(list)
    for sym, hr, tag, r in obs30: cl[(sym, hr, tag)].append(r)
    coll = {t: [st.mean(v) for (s, h, tt), v in cl.items() if tt == t] for t in ("bull", "bear")}
    print("\n=== (2) CLUSTERED by (symbol, hour) at 30m — HONEST ===")
    for t in ("bull", "bear"):
        print(f"  {t:<5} n={len(coll[t]):>4} mean={st.mean(coll[t]):+.3f}% t={tstat(coll[t]):+.2f}")

    real = st.mean(coll["bull"]) - st.mean(coll["bear"])
    pool = coll["bull"] + coll["bear"]; nb = len(coll["bull"])
    random.seed(7); hits = 0; N = 20000
    for _ in range(N):
        random.shuffle(pool)
        if (st.mean(pool[:nb]) - st.mean(pool[nb:])) >= real: hits += 1
    print(f"\n=== (3) PERMUTATION on clustered spread ===")
    print(f"  observed bull-bear spread: {real:+.3f}%   p = {hits/N:.4f}  ({N:,} shuffles)")
    print("\nCAVEAT: labels were LLM-generated by a model aware it was seeking signal.")
    print("A held-out set labelled BEFORE computing returns is required to believe this.")

if __name__ == "__main__":
    if len(sys.argv) != 4: sys.exit(__doc__)
    main(*sys.argv[1:])
